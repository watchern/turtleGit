/** 简体字符串 → 繁体字符串 */
export function toTraditional(s: string): string {
  if (!s) return s;
  let out = s;
  for (const [from, to] of PHRASES) {
    if (out.includes(from)) out = out.split(from).join(to);
  }
  let converted = '';
  for (const ch of out) converted += S2T[ch] ?? ch;
  return converted;
}

